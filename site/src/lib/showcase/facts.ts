/**
 * Бейджи первого экрана и пункты блока «Ваш код и ключи».
 *
 * Почему: утверждение о безопасности без ограничения рядом создаёт ложное
 * впечатление (`AGENTS.md` §2, приоритет 1; design.md redesign-site-showcase,
 * D7, D8). Поэтому у каждого факта есть ссылка на раздел опубликованного
 * документа, а у гарантии с оговоркой в документе — ограничение в той же
 * записи. Слова фактов подтверждаются цитатами документов при сборке (D6):
 * переформулировка документа ломает сборку, и автор витрины сверяет факт.
 *
 * Для чего: `Trust.astro` и `Badges.astro` читают `trustItems` и `badges`;
 * тест `showcase-data.test.ts` проверяет ссылки и тон. Цифр и сравнений с
 * другими продуктами нет (D7).
 *
 * Как использовать: `import { badges, trustItems } from '.../facts'`.
 * Утверждение пишется своими словами по документу; в `verify` — цитаты, в
 * которых документ говорит то же. Окончательный список утверждает проверка
 * фактов `docs-writer` (задача 6.1).
 */
import { quote, type ShowcaseSources } from './sources';

/** Факт: утверждение и раздел-источник; цитаты, подтверждающие слова, передаются в `verify`. */
export interface Fact {
  readonly text: string;
  /** `документ#якорь` опубликованного документа; адрес строит `docRefUrl`. */
  readonly docRef: string;
  /**
   * Якорь на главной странице, куда ведёт бейдж вместо руководства: так
   * гарантия читается рядом со своими ограничениями (D8). `docRef` остаётся
   * для проверки раздела и ссылки «Подробнее».
   */
  readonly homeAnchor?: string;
}

/**
 * Пункт блока доверия: утверждение и ограничения, которые называет документ.
 *
 * Ограничений может быть несколько: проверка фактов 6.1 требует рядом с
 * гарантией назвать каждое, а не одно «главное» (D8).
 */
export interface TrustItem extends Fact {
  readonly limits: readonly Fact[];
}

const privacy = 'apps/codelab_desktop/doc/user/09-settings.md';
const configuration = 'docs/user/configuration.md';
const permissions = 'apps/codelab_agent/doc/user/05-permissions.md';

/**
 * Подтверждает факт цитатами [verify] из [document] и возвращает [fact].
 *
 * Несколько цитат — по одной на каждое слово, которое факт берёт из документа.
 */
function verified<T extends Fact>(
  sources: Pick<ShowcaseSources, 'quote'>,
  document: string,
  verify: readonly string[],
  fact: T,
): T {
  for (const text of verify) sources.quote(document, text);
  return fact;
}

