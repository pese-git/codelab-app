import 'package:test/test.dart';

import '../../tool/gen_prompts.dart';

/// Файл промпта с frontmatter для таблицы ошибок генератора.
String _file({
  String id = 'system.base',
  String vars = '[]',
  String? tools,
  String body = 'Text.',
  String extra = '',
}) =>
    '---\nid: $id\ndescription: d\nvars: $vars\n'
    '${tools == null ? '' : 'tools: $tools\n'}$extra---\n$body\n';

void main() {
  // Ошибки генератора называют путь файла (§11.3, PR-4).
  final errors = <String, Map<String, String>>{
    'no frontmatter': {'system/base.md': 'Just text.\n'},
    'unknown placeholder': {'system/base.md': _file(body: 'Hello {{name}}.')},
    'declared but not used': {'system/base.md': _file(vars: '[name]')},
    'unknown key': {'system/base.md': _file(extra: 'author: me\n')},
    'id differs from the path': {'system/base.md': _file(id: 'system.other')},
    'tools section without tools': {'tools/exec.md': _file(id: 'tools.exec')},
    'bad tool name': {
      'tools/exec.md': _file(id: 'tools.exec', tools: '[exec now]'),
    },
  };

  for (final MapEntry(key: name, value: files) in errors.entries) {
    test('$name is an error with the path', () {
      expect(
        () => generatePrompts(files),
        throwsA(
          isA<PromptGenException>().having(
            (e) => e.message,
            'message',
            startsWith(files.keys.first),
          ),
        ),
      );
    });
  }

  test('a duplicate id is an error with the path', () {
    // Два файла не могут дать один id: id совпадает с путём, поэтому
    // дубликат возможен только через разный регистр сегментов.
    expect(
      () => generatePrompts({
        'tools/a.md': _file(id: 'tools.a', tools: '[read]'),
        'tools/A.md': _file(id: 'tools.a', tools: '[read]'),
      }),
      throwsA(isA<PromptGenException>()),
    );
  });

  test('constants, escaping, tools and the all map', () {
    final out = generatePrompts({
      'tool_descriptions/read.md': _file(
        id: 'tool_descriptions.read',
        vars: '[maxLines]',
        body: "It's \$5 for {{maxLines}} lines.\n\tTab \\ slash\n\n",
      ),
      'tools/edit.md': _file(id: 'tools.edit', tools: '[write, edit]'),
    });

    expect(out, startsWith('// GENERATED by tool/gen_prompts.dart'));
    expect(
      out,
      contains('static const toolDescriptionsRead = PromptTemplate('),
    );
    expect(out, contains("id: 'tool_descriptions.read'"));
    expect(out, contains(r"It\'s \$5 for {{maxLines}} lines.\n\tTab \\ slash"));
    expect(out, isNot(contains(r'slash\n\n')));
    expect(out, contains("tools: {'write', 'edit'}"));
    expect(out, contains("'tools.edit': toolsEdit"));
    // Файлы идут в порядке пути: tool_descriptions раньше tools.
    expect(
      out.indexOf('toolDescriptionsRead ='),
      lessThan(out.indexOf('toolsEdit =')),
    );
  });
}
