import '../llm/model_catalog.dart' show ModelId;

/// Порт памяти последней явно выбранной пользователем модели (design.md
/// change `optional-default-model`, D6).
///
/// Почему порт: когда `agent.default_model` не задан, модель новой сессии
/// выбирается по цепочке «явная → последняя выбранная → первый провайдер»
/// (`selectSessionModel`). Ядро не знает, где хранить «последнюю» (PKG-1:
/// нет `dart:io`), поэтому хост даёт реализацию, а ядро остаётся
/// web-безопасным и без новых зависимостей (PKG-2).
///
/// Для чего: `read` — шаг 2 выбора модели `createSession`; `write` —
/// запоминание явного выбора (`AgentSession.setModel`, `createSession` и
/// `loadSession` с явной моделью). Автоматический выбор, восстановление из
/// журнала и смена агента память НЕ трогают.
///
/// Как использовать: хост кладёт реализацию в `AgentCoreServices.lastModel`
/// (`FileLastModelStore` из `codelab_agent_io`); `null` — памяти нет, шаг 2
/// пропускается. Ядро перехватывает исключения обоих методов и пишет события
/// `model.last_used.ignored` / `model.last_used.write_failed`: сбой памяти не
/// ломает ни выбор, ни смену модели. Реализация не должна выбрасывать
/// содержимое файла и секреты в сообщения.
abstract interface class LastModelStore {
  /// Последняя выбранная модель; `null` — выбора ещё не было или данные
  /// непригодны (реализация сама логирует причину без содержимого).
  Future<ModelId?> read();

  /// Запоминает [model] как последний явный выбор пользователя.
  Future<void> write(ModelId model);
}
