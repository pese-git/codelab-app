import 'mcp_connector.dart';

/// Порт состояния MCP-серверов одной сессии для хоста (design.md change
/// `add-provider-setup-ui`, D12, решение Q18; `17-5-agent-setup.md`, OQ4).
///
/// Почему порт рантайма, а не `McpSessionTools`: `McpSessionTools` у сессии
/// появляется не всегда — без серверов его нет, а первый сервер, добавленный
/// перезагрузкой конфига, создаёт его позже. Хост, взявший порт один раз при
/// открытии страницы, не должен пропустить такой сервер, поэтому порт живёт
/// столько же, сколько сессия, и сам переподписывается на новый
/// `McpSessionTools`.
///
/// Для чего: структурный статус для UI встроенного агента (таблица «Agent
/// status») без ACP и без разбора текста `/mcp list` (SETUP-11).
///
/// Как использовать: `runtime.mcpStatus(sessionId)` возвращает порт у любой
/// открытой сессии. [servers] — снимок (у сессии без серверов пуст),
/// [changes] присылает полный список после каждой смены состояния, числа
/// инструментов, `lastError` или состава серверов, не повторяя последнее
/// значение подписчику, и закрывается вместе с сессией. [reconnect] —
/// действие человека через очередь замен сессии (как `/mcp reload <name>`).
abstract interface class McpStatusPort {
  /// Сводки серверов сессии в порядке списка; пуст, пока серверов нет.
  List<McpServerSummary> get servers;

  /// Широковещательный поток полных списков сводок.
  Stream<List<McpServerSummary>> get changes;

  /// Переподключает сервер [name] сразу, не дожидаясь таймера повтора;
  /// неизвестное имя и закрытая сессия — ничего. Не бросает: сбой — состояние
  /// `failed` и запись в лог.
  Future<void> reconnect(String name);
}
