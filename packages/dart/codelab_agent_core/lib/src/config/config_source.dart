import 'config_issue.dart';

/// Источник конфигурации работающего агента (design.md change
/// `add-config-writer-and-reload`, D7, D8; `agent-core-architecture` §17.5.2).
///
/// Почему порт ядра: файлы, наблюдение за ними и `Clock` debounce — забота
/// хоста (`codelab_agent_io`), а ядру нужны три вещи: результат стартовой
/// загрузки, повторная загрузка и сигнал «файлы изменились». Отступление от
/// §17.5.2: единица перезагрузки — один корень запуска хоста, поэтому у
/// [load] нет параметра `cwd` (D8, «Единица перезагрузки»).
///
/// Для чего: `AgentCoreServices.config` включает живую перезагрузку —
/// рантайм подписывается на [changes] и вызывает [load]. Без источника
/// перезагрузки и команды `/config` нет (`--llm-script`, тесты).
///
/// Как использовать: реализует хост (`FileConfigSource`) и владеет им —
/// создаёт, а после `runtime.dispose()` закрывает. Подписка на [changes]
/// принадлежит рантайму и отменяется в его `dispose()`; сигнал после
/// `dispose()` не приходит. [load] не должен бросать исключений для ошибок
/// конфигурации (они в `ConfigLoadResult.issues`); исключение — сбой
/// чтения, рантайм превратит его в `config.reload.failed` с `error_class`.
abstract interface class ConfigSource {
  /// Результат стартовой загрузки, с которым хост собрал ядро: исходные
  /// `values` и `HostSettings` для первого сравнения и закреплённый список
  /// `config.trustedProjects`.
  ConfigLoadResult get initial;

  /// Повторная загрузка тех же слоёв, окружения и флагов, что при старте.
  ///
  /// Доверие проектам закреплено на [initial] до перезапуска
  /// (`CoreConfig.fromLayers(pinnedTrustedProjects:)`, D8): новое значение
  /// `trusted_projects` попадает только в `ConfigLoadResult.values`.
  ///
  /// [rebase] (D7, D8): `true` — путь перезагрузки; источник принимает
  /// текущее содержимое файлов за «последнюю загрузку» перед чтением, чтобы
  /// ручная перезагрузка не оставила повторный сигнал. `false` — проверка
  /// (`checkConfig`, `/config check`): ничего не применяется, и перенос базы
  /// сравнения в окне debounce терял бы сигнал о правке, которая ещё не
  /// применена. Источнику без наблюдателя параметр безразличен.
  Future<ConfigLoadResult> load({bool rebase = true});

  /// Сигнал «прочитанные файлы изменились» — уже после debounce и сравнения
  /// sha256 (D7). Ошибок поток не несёт.
  Stream<void> get changes;
}
