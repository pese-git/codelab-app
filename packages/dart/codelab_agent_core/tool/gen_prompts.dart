// Генератор констант промптов (`agent-core-architecture` §11.3; design.md
// change `add-agent-core-loop-and-tools`, D11).
//
// Почему кодогенерация: промпт ревьюится как Markdown-документ, а
// исполняется как Dart-константа — на web нет файловой системы, и ядро не
// читает файлы само.
//
// Как использовать (из каталога пакета):
//   fvm dart run tool/gen_prompts.dart          — переписать prompts.g.dart
//   fvm dart run tool/gen_prompts.dart --check  — код выхода 1 при расхождении
import 'dart:io';

import 'package:dart_style/dart_style.dart';

const _output = 'lib/src/prompts/prompts.g.dart';

/// Ошибка исходника промпта; [message] начинается с пути файла (PR-4).
final class PromptGenException implements Exception {
  const PromptGenException(this.message);

  final String message;

  @override
  String toString() => 'PromptGenException: $message';
}

/// Файлы `*.md` под [root] по относительному пути через `/`.
Map<String, String> readPromptFiles(Directory root) {
  final prefix = root.absolute.path.length + 1;
  return {
    for (final file
        in root
            .listSync(recursive: true)
            .whereType<File>()
            .where((f) => f.path.endsWith('.md')))
      file.absolute.path.substring(prefix).replaceAll(r'\', '/'): file
          .readAsStringSync(),
  };
}

final _idPattern = RegExp(r'^[a-z0-9._]+$');
final _toolName = RegExp(r'^[a-zA-Z0-9_-]{1,64}$');
final _varName = RegExp(r'^[A-Za-z][A-Za-z0-9_]*$');
final _placeholder = RegExp(r'(\\?)\{\{([^}]*)\}\}');

/// Текст `prompts.g.dart` по файлам [files] (путь → содержимое).
///
/// Чистая функция: тест синхронизации (PR-1) вызывает её без процесса и
/// сравнивает результат с файлом на диске.
String generatePrompts(Map<String, String> files) {
  final paths = files.keys.toList()..sort();
  final seen = <String, String>{};
  final constants = <String>[];
  final all = <String>[];
  for (final path in paths) {
    final prompt = _parse(path, files[path]!);
    if (seen[prompt.id] case final other?) {
      throw PromptGenException(
        '$path: duplicate id ${prompt.id} (also $other)',
      );
    }
    seen[prompt.id] = path;
    final expectedId = path.substring(0, path.length - 3).replaceAll('/', '.');
    if (prompt.id != expectedId) {
      throw PromptGenException(
        '$path: id ${prompt.id} must match the path ($expectedId)',
      );
    }
    final name = _constName(path);
    constants.add(
      'static const $name = PromptTemplate('
      "id: '${prompt.id}', "
      'vars: {${prompt.vars.map((v) => "'$v'").join(', ')}}, '
      '${prompt.tools.isEmpty ? '' : "tools: {${prompt.tools.map((t) => "'$t'").join(', ')}}, "}'
      "text: '${_escape(prompt.body)}',"
      ');',
    );
    all.add("'${prompt.id}': $name,");
  }
  final source =
      '// GENERATED by tool/gen_prompts.dart from prompts/**/*.md. Do not edit by hand.\n'
      '// ignore_for_file: lines_longer_than_80_chars\n'
      "import 'template.dart';\n\n"
      '/// Тексты промптов ядра: константы из `prompts/**/*.md` (§11.2).\n'
      'abstract final class Prompts {\n'
      '${constants.join('\n')}\n'
      'static const all = <String, PromptTemplate>{${all.join(' ')}};\n'
      '}\n';
  return DartFormatter(
    languageVersion: DartFormatter.latestLanguageVersion,
  ).format(source);
}

final class _Prompt {
  _Prompt(this.id, this.vars, this.tools, this.body);

  final String id;
  final List<String> vars;
  final List<String> tools;
  final String body;
}

_Prompt _parse(String path, String content) {
  final lines = content.replaceAll('\r\n', '\n').split('\n');
  final close = lines.indexOf('---', 1);
  if (lines.isEmpty || lines.first != '---' || close < 0) {
    throw PromptGenException('$path: no frontmatter');
  }
  String? id;
  String? description;
  List<String>? vars;
  List<String>? tools;
  for (final line in lines.sublist(1, close)) {
    final colon = line.indexOf(': ');
    final key = colon < 0 ? line : line.substring(0, colon);
    final value = colon < 0 ? '' : line.substring(colon + 2).trim();
    switch (key) {
      case 'id' when _idPattern.hasMatch(value):
        id = value;
      case 'description' when value.isNotEmpty:
        description = value;
      case 'vars':
        vars = _list(path, key, value, _varName);
      case 'tools':
        tools = _list(path, key, value, _toolName);
      default:
        throw PromptGenException('$path: unknown frontmatter line "$line"');
    }
  }
  if (id == null || description == null || vars == null) {
    throw PromptGenException('$path: id, description and vars are required');
  }
  if (path.startsWith('tools/') && (tools == null || tools.isEmpty)) {
    throw PromptGenException('$path: a tools section without tools');
  }
  // Тело: текст после закрывающего `---`; завершающие пустые строки
  // обрезаются, перевод строки в конце не добавляется (§11.3, шаг 2c).
  final body = lines.sublist(close + 1).join('\n').trimRight();
  final used = {
    for (final m in _placeholder.allMatches(body))
      if (m[1]!.isEmpty) m[2]!,
  };
  for (final name in used) {
    if (!_varName.hasMatch(name)) {
      throw PromptGenException('$path: bad placeholder {{$name}}');
    }
  }
  final unknown = used.difference(vars.toSet());
  if (unknown.isNotEmpty) {
    throw PromptGenException(
      '$path: unknown placeholder ${unknown.map((v) => '{{$v}}').join(', ')}',
    );
  }
  final unused = vars.toSet().difference(used);
  if (unused.isNotEmpty) {
    throw PromptGenException(
      '$path: declared but not used: ${unused.join(', ')}',
    );
  }
  return _Prompt(id, vars, tools ?? const [], body);
}

List<String> _list(String path, String key, String value, RegExp item) {
  if (!value.startsWith('[') || !value.endsWith(']')) {
    throw PromptGenException('$path: $key must be a list [a, b]');
  }
  final inner = value.substring(1, value.length - 1).trim();
  final items = inner.isEmpty
      ? const <String>[]
      : [for (final part in inner.split(',')) part.trim()];
  for (final name in items) {
    if (!item.hasMatch(name)) {
      throw PromptGenException('$path: bad $key entry "$name"');
    }
  }
  return items;
}

/// `system/base.md` → `systemBase`, `tool_descriptions/update_plan.md` →
/// `toolDescriptionsUpdatePlan`.
String _constName(String path) {
  final parts = path
      .substring(0, path.length - 3)
      .split(RegExp('[/_]'))
      .where((p) => p.isNotEmpty)
      .toList();
  return [
    parts.first,
    for (final part in parts.skip(1)) part[0].toUpperCase() + part.substring(1),
  ].join();
}

/// Одинарно-кавычечный литерал Dart: raw-строки не годятся, в тексте может
/// встретиться `'''` (§11.3).
String _escape(String text) => text
    .replaceAll(r'\', r'\\')
    .replaceAll("'", r"\'")
    .replaceAll(r'$', r'\$')
    .replaceAll('\n', r'\n')
    .replaceAll('\r', r'\r')
    .replaceAll('\t', r'\t');

void main(List<String> args) {
  final check = args.contains('--check');
  final String generated;
  try {
    generated = generatePrompts(readPromptFiles(Directory('prompts')));
  } on PromptGenException catch (error) {
    stderr.writeln(error.message);
    exitCode = 1;
    return;
  }
  final out = File(_output);
  if (check) {
    if (!out.existsSync() || out.readAsStringSync() != generated) {
      stderr.writeln('$_output is out of date: run tool/gen_prompts.dart');
      exitCode = 1;
    }
    return;
  }
  out.writeAsStringSync(generated);
}
