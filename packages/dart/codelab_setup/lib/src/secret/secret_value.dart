/// Значение секрета в памяти клиента (client-agent-setup «Значение секрета в
/// памяти клиента»; `dart-agent-and-clients` §12.4.2; SETUP-1).
library;

/// Значение ключа или токена, которое нельзя случайно напечатать.
///
/// Почему отдельный тип: ключ провайдера проходит через несколько слоёв —
/// поле ввода, мастер, проверка `/models`, запись в хранилище, — и каждый
/// `toString()`, JSON или `$value` в сообщении об ошибке мог бы унести его в
/// журнал, состояние Cubit или отчёт о сбое. Обёртка делает утечку
/// невозможной по умолчанию: значение достаётся только явным [reveal].
///
/// Для чего: единственное представление секрета в мосте настроек и в
/// интерфейсе `ProviderCheck`. Хранилище секретов (`ClientSecretAccess`) отдаёт
/// `String?` адаптеру composition root, а тот сразу оборачивает его.
///
/// Как использовать: `SecretValue(text)` создаёт тот, кто получил значение
/// (поле ввода, адаптер хранилища); [reveal] вызывает только код, который
/// отправляет значение по назначению — заголовок запроса или запись в
/// хранилище. [toString] и [toJson] дают `***`.
final class SecretValue {
  SecretValue(this._value);

  final String _value;

  /// Значение. Вызывать только в месте отправки; результат нельзя сохранять
  /// в состоянии, событиях и текстах (SETUP-1).
  String reveal() => _value;

  /// Пустое ли значение: пустой ключ — ошибка шага, а не «ключ не нужен».
  bool get isEmpty => _value.isEmpty;

  /// `***` для `jsonEncode`, чтобы значение не попало в сериализацию.
  String toJson() => '***';

  @override
  String toString() => '***';
}
