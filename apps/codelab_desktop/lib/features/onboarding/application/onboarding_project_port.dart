/// Порт шага «Open a project» onboarding (design.md change
/// `add-onboarding-project-step`, D5).
///
/// Почему порт: application onboarding не зависит от application рабочего
/// места, а правило «что считается принятой папкой» уже есть в
/// `SettingsCubit` (диалог, перетаскивание, недавние) и второй копии не
/// получает. Тест `OnboardingCubit` обходится одной подделкой порта, без графа
/// рабочего места (по образцу `OnboardingProbe`).
///
/// Для чего: шаг завершается только по принятому выбору, поэтому методы
/// возвращают путь принятой папки или `null` (отмена, сбой, отказ броска —
/// текст отказа уже в состоянии рабочего места и показывается в зоне шага).
/// Принятый выбор порт применяет сразу (проект выбран, недавние записаны),
/// но агента не стартует: пока показан onboarding, триггер старта удержан
/// (`SettingsCubit.projectStartHeld`, D5).
///
/// Как использовать: адаптер `lib/app/onboarding_project_port.dart` строится
/// поверх фасада `CodeLabShellCubit` и привязывается в `app_scope.dart`;
/// `OnboardingCubit` вызывает методы не более чем по одному за раз.
abstract interface class OnboardingProjectPort {
  /// Системный выбор папки: путь принятой папки или `null` (диалог закрыт без
  /// выбора, сбой диалога).
  Future<String?> pickFolder();

  /// Папка, брошенная на экран: путь принятой папки или `null` при отказе
  /// (файл, несколько элементов, пропавший путь, не локальный путь).
  Future<String?> openDropped(List<String?> paths);

  /// Недавний проект [path]: путь выбранной папки или `null`.
  Future<String?> openRecent(String path);

  /// Выбранный проект (в том числе восстановленный из снимка) или `null`.
  String? get selectedProject;
}
